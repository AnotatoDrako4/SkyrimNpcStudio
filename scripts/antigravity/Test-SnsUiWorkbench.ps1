<#
.SYNOPSIS
  Antigravity Real-Window Workbench Verification Auditor (AG-UI-WORKBENCH).
  Executes real-window Qt Quick 3D Workbench automation with mouse/keyboard input:
  - Panel resizing and SplitView persistence
  - Minimizing/maximizing 3D viewer (F11)
  - Layout persistence across restart (run1 -> restart expect.json comparison)
  - UI scaling (85% to 150%) and font scaling (80% to 160%)
  - Safe isolated run directory (never modifies registry or user preferences).
  NO GIT / NO GITHUB.
#>
[CmdletBinding()]
param(
    [string]$Size = '1366x768',
    [string]$Instance = 'D:\Apps\ModOrganizer.ini',
    [string]$MO2Profile = 'Default',
    [string]$Npc = '002B6C:Dawnguard.esm',
    [string]$Preset = 'debug',
    [string]$DisplayScale,
    [string]$OutputDir
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)

$devEnv = Join-Path $repoRoot 'scripts\dev-env.ps1'
if (Test-Path $devEnv) {
    . $devEnv | Out-Null
}

$exe = Join-Path $repoRoot "build\$Preset\bin\SkyrimNpcStudio.exe"
if (-not (Test-Path $exe)) {
    throw "SkyrimNpcStudio.exe not found at $exe"
}

$label = "workbench-$Size$(if ($DisplayScale) { "-dpi$DisplayScale" })"
if (-not $OutputDir) {
    $OutputDir = Join-Path $repoRoot "out\ui\$label"
}
$settingsDir = Join-Path $OutputDir 'settings'
if (-not (Test-Path $settingsDir)) {
    New-Item -ItemType Directory -Path $settingsDir -Force | Out-Null
}

$env:SNS_SETTINGS_DIR = $settingsDir
$previousScale = $env:QT_SCALE_FACTOR
if ($DisplayScale) { $env:QT_SCALE_FACTOR = $DisplayScale }

Write-Host "=== [AG-UI-WORKBENCH] Real-Window Workbench UI 2.0 Auditor ===" -ForegroundColor Cyan
Write-Host "Executable: $exe" -ForegroundColor Gray
Write-Host "Output: $OutputDir" -ForegroundColor Gray

function Invoke-WorkbenchRun([string]$name, [string[]]$extraArgs) {
    $runOut = Join-Path $OutputDir $name
    if (-not (Test-Path $runOut)) { New-Item -ItemType Directory -Path $runOut -Force | Out-Null }
    $logPath = Join-Path $OutputDir "$name.log"
    $screenPath = Join-Path $OutputDir "$name-final.png"

    $argList = @(
        '--instance', "`"$Instance`"",
        '--profile', "`"$MO2Profile`"",
        '--npc', "`"$Npc`"",
        '--smoke-size', $Size,
        '--screenshot', "`"$screenPath`""
    ) + $extraArgs

    $psi = New-Object System.Diagnostics.ProcessStartInfo
    $psi.FileName = $exe
    $psi.Arguments = $argList -join ' '
    $psi.UseShellExecute = $false
    $psi.RedirectStandardError = $true
    $psi.RedirectStandardOutput = $true
    $psi.WindowStyle = [System.Diagnostics.ProcessWindowStyle]::Normal

    $proc = [System.Diagnostics.Process]::Start($psi)
    $stderr = $proc.StandardError.ReadToEndAsync()
    $stdout = $proc.StandardOutput.ReadToEndAsync()
    $proc.WaitForExit()

    $allOutput = "$($stdout.Result)`n$($stderr.Result)"
    Set-Content -Path $logPath -Value $allOutput -Encoding utf8

    $passed = $allOutput -match 'summary:\s*PASSED'
    Write-Host "[$name] Process ExitCode: $($proc.ExitCode) | Summary Passed: $passed" -ForegroundColor $(if ($passed) { "Green" } else { "Red" })

    return [PSCustomObject]@{
        Name = $name
        ExitCode = $proc.ExitCode
        Passed = $passed
        LogPath = $logPath
    }
}

try {
    $run1Out = Join-Path $OutputDir 'run1'
    $r1 = Invoke-WorkbenchRun 'run1' @('--workbench-check', "`"$run1Out`"")

    $expectJson = Join-Path $run1Out 'expect.json'
    if (-not (Test-Path $expectJson)) {
        throw "expect.json was not generated by run1 at $expectJson"
    }

    $restartOut = Join-Path $OutputDir 'restart'
    $r2 = Invoke-WorkbenchRun 'restart' @('--workbench-check', "`"$restartOut`"", '--workbench-expect', "`"$expectJson`"")

    $allPassed = $r1.Passed -and $r2.Passed
    $result = [PSCustomObject]@{
        Suite = "AG-UI-WORKBENCH"
        Timestamp = [DateTime]::UtcNow.ToString("o")
        AllPassed = $allPassed
        Run1 = $r1
        Restart = $r2
        ExpectationsVerified = (Test-Path $expectJson)
    }

    $summaryJson = Join-Path $OutputDir 'workbench-audit-summary.json'
    $result | ConvertTo-Json -Depth 5 | Set-Content -Path $summaryJson -Encoding utf8

    if (-not $allPassed) {
        throw "Workbench UI verification failed (run1=$($r1.Passed), restart=$($r2.Passed))"
    }

    Write-Host "=== Real-Window Workbench UI 2.0 Verification: PASS ===" -ForegroundColor Green
    return $result
} finally {
    Remove-Item Env:\SNS_SETTINGS_DIR -ErrorAction SilentlyContinue
    $env:QT_SCALE_FACTOR = $previousScale
}
