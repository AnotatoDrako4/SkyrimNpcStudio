def write_file(root: Path, relative: str, content: bytes | str) -> Path:
    """Create ``root/relative`` with its parents, accepting text or raw bytes."""
    target = root / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(content, str):
        target.write_text(content, encoding="utf-8")
    else:
        target.write_bytes(content)
    return target


def build_instance(
    base: Path,
    mods: dict[str, dict[str, bytes | str]],
    modlist: list[str],
    *,
    profile: str = "TestProfile",
    extra_profiles: dict[str, list[str]] | None = None,
    plugins: list[str] | None = None,
    overwrite: dict[str, bytes | str] | None = None,
) -> Path:
    """Lay out a portable MO2 instance under ``base`` and return the instance dir.

    ``modlist`` is given top-down exactly as MO2 writes it, so the first entry is
    the HIGHEST priority. Entries carry their own ``+``/``-``/``*``/``#`` marker.
    """
    base.mkdir(parents=True, exist_ok=True)
    (base / "mods").mkdir(exist_ok=True)
    (base / "profiles").mkdir(exist_ok=True)
    (base / "overwrite").mkdir(exist_ok=True)

    for mod_name, files in mods.items():
        mod_root = base / "mods" / mod_name
        mod_root.mkdir(parents=True, exist_ok=True)
        for relative, content in files.items():
            write_file(mod_root, relative, content)

    for relative, content in (overwrite or {}).items():
        write_file(base / "overwrite", relative, content)

    all_profiles = {profile: modlist}
    all_profiles.update(extra_profiles or {})
    for name, rows in all_profiles.items():
        profile_dir = base / "profiles" / name
        profile_dir.mkdir(parents=True, exist_ok=True)
        header = "# This file was automatically generated by Mod Organizer.\n"
        (profile_dir / "modlist.txt").write_text(header + "\n".join(rows) + "\n", encoding="utf-8")
        if plugins is not None:
            (profile_dir / "plugins.txt").write_text("\n".join(plugins) + "\n", encoding="utf-8")

    ini = (
        "[General]\n"
        "gameName=Skyrim Special Edition\n"
        f"selected_profile=@ByteArray({profile})\n"
        "gamePath=@ByteArray(D:\\\\SyntheticFixture\\\\Skyrim Special Edition)\n"
        "\n[Settings]\n"
        f"base_directory={base.as_posix()}\n"
    )
    (base / "ModOrganizer.ini").write_text(ini, encoding="utf-8")
    return base


class FixtureCase(unittest.TestCase):
    """Base case giving each test an isolated temporary instance root."""

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory(prefix="anim-lab-")
        self.tmp = Path(self._tmp.name)
        self.budget = TEST_BUDGET

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def load(self, instance_dir: Path, profile: str = "TestProfile"):
        """Return ``(instance, profile)`` for a fixture built by :func:`build_instance`."""
        instance = mo2_profile.load_instance(instance_dir, self.budget)
        return instance, mo2_profile.load_profile(instance, profile, self.budget)
