import tempfile
import unittest
from pathlib import Path

TOOL_ROOT = Path(__file__).resolve().parents[2] / "tools" / "claude-animation-intelligence"
if str(TOOL_ROOT) not in sys.path:
    sys.path.insert(0, str(TOOL_ROOT))

from engine import mo2_profile  # noqa: E402
from engine.sandbox import Budget  # noqa: E402

# Small budgets keep the suite fast; security tests override them explicitly.
TEST_BUDGET = Budget(max_files=20_000, max_seconds=120.0, max_html_rows=200)

