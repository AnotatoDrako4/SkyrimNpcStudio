"""MO2 profile semantics: cases M01, M03, M04, M09.

Each test name carries its mission case id so ``test-results.txt`` maps 1:1 to
the acceptance matrix.
"""

from __future__ import annotations

import unittest

from _support import MT_IDLE, FixtureCase, build_instance
from engine import mo2_profile
from engine.mo2_profile import ProfileError, parse_modlist


class ModlistOrderTests(unittest.TestCase):
    """M01: the first line of modlist.txt is the HIGHEST priority."""

    def test_M01_first_line_is_highest_priority(self) -> None:
        mods = parse_modlist("+Top\n+Middle\n+Bottom\n")
        by_name = {m.name: m.priority for m in mods}
        self.assertEqual(by_name["Bottom"], 0)
        self.assertEqual(by_name["Middle"], 1)
        self.assertEqual(by_name["Top"], 2)
        self.assertGreater(by_name["Top"], by_name["Bottom"])

    def test_M01_comments_and_blank_lines_are_not_mods(self) -> None:
        mods = parse_modlist("# generated by Mod Organizer\n\n+Only\n   \n")
        self.assertEqual([m.name for m in mods], ["Only"])

    def test_M03_disabled_entry_is_never_a_provider(self) -> None:
        mods = parse_modlist("+On\n-Off\n")
        off = next(m for m in mods if m.name == "Off")
        self.assertFalse(off.enabled)
        self.assertFalse(off.is_provider)

    def test_M04_separator_is_not_a_data_provider(self) -> None:
        mods = parse_modlist("+Real\n+Scenery_separator\n")
        separator = next(m for m in mods if m.name == "Scenery_separator")
        self.assertEqual(separator.kind, "separator")
        self.assertTrue(separator.enabled)
        self.assertFalse(separator.is_provider, "a separator must never supply files")

    def test_M04_foreign_star_entry_is_flagged_not_dropped(self) -> None:
        mods = parse_modlist("*Unmanaged DLC\n+Real\n")
        foreign = next(m for m in mods if m.name == "Unmanaged DLC")
        self.assertEqual(foreign.kind, "foreign")
        self.assertFalse(foreign.is_provider)

    def test_M04_unknown_marker_is_ignored_rather_than_guessed(self) -> None:
        self.assertEqual(parse_modlist("?Mystery\n+Real\n"), parse_modlist("+Real\n"))


class InstanceLoadingTests(FixtureCase):
    """Instance resolution and the empty-profile case M09."""

    def test_instance_resolves_bytearray_and_derived_directories(self) -> None:
        root = build_instance(self.tmp / "inst", {"ModA": {MT_IDLE: b"A"}}, ["+ModA"])
        instance = mo2_profile.load_instance(root, self.budget)
        self.assertEqual(instance.game_name, "Skyrim Special Edition")
        self.assertEqual(instance.selected_profile, "TestProfile")
        self.assertIn("Skyrim Special Edition", instance.game_path)
        self.assertEqual(instance.mods_dir, root / "mods")
        self.assertEqual(instance.profiles_dir, root / "profiles")
        self.assertEqual(instance.overwrite_dir, root / "overwrite")

    def test_M09_profile_with_no_enabled_mods_yields_no_providers(self) -> None:
        root = build_instance(self.tmp / "inst", {"ModA": {MT_IDLE: b"A"}}, ["-ModA"])
        _, profile = self.load(root)
        self.assertEqual(profile.providers, [])
        self.assertEqual(profile.enabled_count, 0)
        self.assertEqual(profile.disabled_names, ["ModA"])

    def test_profile_listing_sees_every_profile_with_a_modlist(self) -> None:
        root = build_instance(
            self.tmp / "inst",
            {"ModA": {MT_IDLE: b"A"}},
            ["+ModA"],
            profile="Default",
            extra_profiles={"BodyChangeNG-Test": ["+ModA"]},
        )
        instance = mo2_profile.load_instance(root, self.budget)
        self.assertEqual(instance.profile_names(), ["BodyChangeNG-Test", "Default"])

    def test_missing_profile_raises_rather_than_inventing_one(self) -> None:
        root = build_instance(self.tmp / "inst", {"ModA": {MT_IDLE: b"A"}}, ["+ModA"])
        instance = mo2_profile.load_instance(root, self.budget)
        with self.assertRaises(ProfileError):
            mo2_profile.load_profile(instance, "NoSuchProfile", self.budget)

    def test_primary_plugins_are_base_masters_plus_skyrim_ccc(self) -> None:
        root = build_instance(self.tmp / "inst", {"ModA": {MT_IDLE: b"A"}}, ["+ModA"])
        instance = mo2_profile.load_instance(root, self.budget)
        game = self.tmp / "game"
        game.mkdir()
        (game / "Skyrim.ccc").write_text(
            "ccQDRSSE001-SurvivalMode.esl\r\nccBGSSSE001-Fish.esm\r\n\r\n", encoding="utf-8"
        )
        instance.game_path = str(game)
        primary, source = mo2_profile.primary_plugins(instance, self.budget)
        self.assertIn("skyrim.esm", primary)
        self.assertIn("dragonborn.esm", primary)
        self.assertIn("ccqdrsse001-survivalmode.esl", primary)
        self.assertIn("ccbgssse001-fish.esm", primary)
        self.assertEqual(len(primary), 7)
        self.assertIn("Skyrim.ccc", source)

    def test_primary_plugins_without_a_game_folder_fall_back_to_base_masters(self) -> None:
        root = build_instance(self.tmp / "inst", {"ModA": {MT_IDLE: b"A"}}, ["+ModA"])
        instance = mo2_profile.load_instance(root, self.budget)
        primary, source = mo2_profile.primary_plugins(instance, self.budget)
        self.assertEqual(primary, mo2_profile.BASE_MASTERS)
        self.assertIn("base masters only", source)

    def test_missing_modorganizer_ini_raises(self) -> None:
        empty = self.tmp / "empty"
        empty.mkdir()
        with self.assertRaises(ProfileError):
            mo2_profile.load_instance(empty, self.budget)


if __name__ == "__main__":
    unittest.main()
