    public const uint LightRangeMin = 0x800;
    public const uint LightRangeMax = 0xFFF;

    public static BuiltPatch BuildFaceOverhaul(
        LoadOrderSession session, CatalogQueries queries, ExportFaceOverhaulRequest request,
        string stagedPluginPath, string stagedModDir, CancellationToken ct)
    {
        OutfitPatchBuilder.ValidatePluginName(request.PluginName, session);
        if (request.Assignments.Count == 0)
        {
            throw new WorkerException(ErrorCodes.InvalidArgument, "At least one face assignment is required.");
        }

        var issues = new List<Issue>();
        var patchKey = ModKey.FromFileName(request.PluginName);
        var patch = new SkyrimMod(patchKey, SkyrimRelease.SkyrimSE);
        patch.ModHeader.Author = Truncate(request.Author, 255);
        patch.ModHeader.Description = Truncate(request.Description ?? "Generated by Skyrim NPC Studio (Face Overhaul)", 511);
        if (request.EslFlag)
        {
            patch.ModHeader.Flags |= SkyrimModHeader.HeaderFlag.Small;
        }

        var records = new List<ExportedRecord>();
        var builtAssignments = new List<BuiltAssignment>();
        var npcsSeen = new HashSet<FormKey>();

        foreach (var assignment in request.Assignments)
        {
            ct.ThrowIfCancellationRequested();
            if (!queries.TryParseAnyFormKey(assignment.NpcFormKey, out var npcKey)
                || !session.LinkCache.TryResolve<INpcGetter>(npcKey, out var targetNpc))
            {
                issues.Add(Issue.Error("TargetNpcNotFound", $"Target NPC not found in active load order: '{assignment.NpcFormKey}'."));
                continue;
            }

            if (!npcsSeen.Add(npcKey))
            {
                issues.Add(Issue.Error("DuplicateNpc", "The same NPC has two assignments in one patch.", npcKey.ToString()));
                continue;
            }

            var npcOverride = patch.Npcs.GetOrAddAsOverride(targetNpc);
            ApplyFaceCustomization(session, queries, assignment, npcOverride, issues);
            StageFaceGenFiles(session, queries, assignment, npcKey, stagedModDir, issues);

            records.Add(new ExportedRecord { FormKey = targetNpc.FormKey.ToString(), RecordType = "NPC_", EditorId = targetNpc.EditorID, Kind = "override" });
            builtAssignments.Add(new BuiltAssignment(targetNpc.FormKey, targetNpc.EditorID, targetNpc.Name?.String, FormKey.Null, "", []));
        }

        if (issues.Any(i => i.Severity == "error"))
        {
            throw new WorkerException(ErrorCodes.ValidationFailed, "Validation failed; nothing was written.", issues);
        }

        var loadOrderKeys = session.Plugins.Select(p => p.ModKey).ToArray();
        patch.WriteToBinary(stagedPluginPath, new BinaryWriteParameters
        {
            MastersListOrdering = new MastersListOrderingByLoadOrder(loadOrderKeys),
            MasterFlagsLookup = session.MasterStyles,
        });

        var masters = Verify(session, stagedPluginPath, patchKey, builtAssignments.Count, request.EslFlag, issues);
        return new BuiltPatch(stagedPluginPath, masters, request.EslFlag, records, builtAssignments, issues);
    }

    public static BuiltPatch BuildCompleteOverhaul(
        LoadOrderSession session, CatalogQueries queries, ExportCompleteOverhaulRequest request,
        string stagedPluginPath, string stagedModDir, CancellationToken ct)
    {
        OutfitPatchBuilder.ValidatePluginName(request.PluginName, session);
        if (request.Assignments.Count == 0)
        {
            throw new WorkerException(ErrorCodes.InvalidArgument, "At least one complete NPC assignment is required.");
        }

        var issues = new List<Issue>();
        var patchKey = ModKey.FromFileName(request.PluginName);
        var patch = new SkyrimMod(patchKey, SkyrimRelease.SkyrimSE);
        patch.ModHeader.Author = Truncate(request.Author, 255);
        patch.ModHeader.Description = Truncate(request.Description ?? "Generated by Skyrim NPC Studio (Complete Overhaul)", 511);
        if (request.EslFlag)
        {
            patch.ModHeader.Flags |= SkyrimModHeader.HeaderFlag.Small;
        }

        var records = new List<ExportedRecord>();
        var builtAssignments = new List<BuiltAssignment>();
        var npcsSeen = new HashSet<FormKey>();
        var usedEditorIds = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        foreach (var item in request.Assignments)
        {
            ct.ThrowIfCancellationRequested();
            if (!queries.TryParseAnyFormKey(item.NpcFormKey, out var npcKey)
                || !session.LinkCache.TryResolve<INpcGetter>(npcKey, out var targetNpc))
            {
                issues.Add(Issue.Error("TargetNpcNotFound", $"Target NPC not found in active load order: '{item.NpcFormKey}'."));
                continue;
            }

            if (!npcsSeen.Add(npcKey))
            {
                issues.Add(Issue.Error("DuplicateNpc", "The same NPC has two assignments in one patch.", npcKey.ToString()));
                continue;
            }

            var npcOverride = patch.Npcs.GetOrAddAsOverride(targetNpc);
            FormKey outfitKey = FormKey.Null;
            string outfitEditorId = "";
            var piecesList = new List<ArmorSummary>();

            if (item.Outfit is { } outfitAssignment && outfitAssignment.ArmorFormKeys.Count > 0)
            {
                var validation = OutfitValidator.Validate(session, queries, new OutfitValidateRequest
                {
                    NpcFormKey = outfitAssignment.NpcFormKey,
                    ArmorFormKeys = outfitAssignment.ArmorFormKeys,
                });
                issues.AddRange(validation.Issues.Where(i => i.Code != "SaveGamePersistence"));
                if (validation.Exportable)
                {
                    outfitEditorId = UniqueEditorId(outfitAssignment.OutfitEditorId ?? $"SNS_{targetNpc.EditorID ?? targetNpc.FormKey.ID.ToString("X6")}Outfit", usedEditorIds);
                    var outfit = patch.Outfits.AddNew(outfitEditorId);
                    outfit.Items = new ExtendedList<IFormLinkGetter<IOutfitTargetGetter>>(
                        validation.Pieces.Select(p => (IFormLinkGetter<IOutfitTargetGetter>)new FormLink<IOutfitTargetGetter>(FormKey.Factory(p.Armor.FormKey))));
                    outfitKey = outfit.FormKey;

                    npcOverride.DefaultOutfit.SetTo(outfitKey);
                    if (outfitAssignment.AlsoSetSleepingOutfit)
                    {
                        npcOverride.SleepingOutfit.SetTo(outfitKey);
                    }

                    records.Add(new ExportedRecord { FormKey = outfitKey.ToString(), RecordType = "OTFT", EditorId = outfitEditorId, Kind = "new" });
                    piecesList.AddRange(validation.Pieces.Select(p => p.Armor));
                }
            }

            if (item.Face is { } faceAssignment)
            {
                ApplyFaceCustomization(session, queries, faceAssignment, npcOverride, issues);
                StageFaceGenFiles(session, queries, faceAssignment, npcKey, stagedModDir, issues);
            }

            records.Add(new ExportedRecord { FormKey = targetNpc.FormKey.ToString(), RecordType = "NPC_", EditorId = targetNpc.EditorID, Kind = "override" });
            builtAssignments.Add(new BuiltAssignment(targetNpc.FormKey, targetNpc.EditorID, targetNpc.Name?.String, outfitKey, outfitEditorId, piecesList));
        }

        if (issues.Any(i => i.Severity == "error"))
        {
            throw new WorkerException(ErrorCodes.ValidationFailed, "Validation failed; nothing was written.", issues);
        }

        if (request.EslFlag)
        {
            foreach (var record in patch.EnumerateMajorRecords().Where(r => r.FormKey.ModKey == patchKey))
            {
                if (record.FormKey.ID is < LightRangeMin or > LightRangeMax)
                {
                    throw new WorkerException(ErrorCodes.ValidationFailed,
                        $"ESL flag rejected: new record {record.FormKey} is outside the light-plugin range 0x800–0xFFF.");
                }
            }
        }

        var loadOrderKeys = session.Plugins.Select(p => p.ModKey).ToArray();
        patch.WriteToBinary(stagedPluginPath, new BinaryWriteParameters
        {
            MastersListOrdering = new MastersListOrderingByLoadOrder(loadOrderKeys),
            MasterFlagsLookup = session.MasterStyles,
        });

        var masters = Verify(session, stagedPluginPath, patchKey, builtAssignments.Count, request.EslFlag, issues);
        return new BuiltPatch(stagedPluginPath, masters, request.EslFlag, records, builtAssignments, issues);
    }

    private static void ApplyFaceCustomization(
        LoadOrderSession session, CatalogQueries queries, FaceAssignment assignment, Npc npcOverride, List<Issue> issues)
    {
        // 1. If donor NPC is specified, copy donor baseline
        if (!string.IsNullOrWhiteSpace(assignment.DonorNpcFormKey)
            && queries.TryParseAnyFormKey(assignment.DonorNpcFormKey, out var donorKey)
            && session.LinkCache.TryResolve<INpcGetter>(donorKey, out var donorNpc))
        {
            npcOverride.HeadParts.Clear();
            foreach (var hp in donorNpc.HeadParts)
            {
                npcOverride.HeadParts.Add(new FormLink<IHeadPartGetter>(hp.FormKey));
            }

            if (donorNpc.HairColor.FormKeyNullable is { } hairColorKey)
            {
                npcOverride.HairColor.SetTo(hairColorKey);
            }

            if (donorNpc.TextureLighting is { } lighting)
            {
                npcOverride.TextureLighting = lighting;
            }

            if (donorNpc.FaceMorph is { } dfm)
            {
                npcOverride.FaceMorph ??= new NpcFaceMorph();
                npcOverride.FaceMorph.NoseLongVsShort = dfm.NoseLongVsShort;
                npcOverride.FaceMorph.NoseUpVsDown = dfm.NoseUpVsDown;
                npcOverride.FaceMorph.JawUpVsDown = dfm.JawUpVsDown;
                npcOverride.FaceMorph.JawNarrowVsWide = dfm.JawNarrowVsWide;
                npcOverride.FaceMorph.JawForwardVsBack = dfm.JawForwardVsBack;
                npcOverride.FaceMorph.CheeksUpVsDown = dfm.CheeksUpVsDown;
                npcOverride.FaceMorph.CheeksForwardVsBack = dfm.CheeksForwardVsBack;
                npcOverride.FaceMorph.EyesUpVsDown = dfm.EyesUpVsDown;
                npcOverride.FaceMorph.EyesInVsOut = dfm.EyesInVsOut;
                npcOverride.FaceMorph.EyesForwardVsBack = dfm.EyesForwardVsBack;
                npcOverride.FaceMorph.BrowsUpVsDown = dfm.BrowsUpVsDown;
                npcOverride.FaceMorph.BrowsInVsOut = dfm.BrowsInVsOut;
                npcOverride.FaceMorph.BrowsForwardVsBack = dfm.BrowsForwardVsBack;
                npcOverride.FaceMorph.LipsUpVsDown = dfm.LipsUpVsDown;
                npcOverride.FaceMorph.LipsInVsOut = dfm.LipsInVsOut;
                npcOverride.FaceMorph.ChinNarrowVsWide = dfm.ChinNarrowVsWide;
                npcOverride.FaceMorph.ChinUpVsDown = dfm.ChinUpVsDown;
                npcOverride.FaceMorph.ChinUnderbiteVsOverbite = dfm.ChinUnderbiteVsOverbite;
            }

            if (donorNpc.FaceParts is { } dfp)
            {
                npcOverride.FaceParts = new NpcFaceParts { Nose = dfp.Nose, Eyes = dfp.Eyes, Mouth = dfp.Mouth };
            }

            if (donorNpc.TintLayers is { } dtl)
            {
                npcOverride.TintLayers.Clear();
                foreach (var t in dtl)
                {
                    npcOverride.TintLayers.Add(new TintLayer
                    {
                        Index = t.Index,
                        Color = t.Color,
                        InterpolationValue = t.InterpolationValue,
                        Preset = t.Preset,
                    });
                }
            }

            npcOverride.Weight = donorNpc.Weight;
            npcOverride.Height = donorNpc.Height;
        }

        // 2. Explicit HeadParts override
        if (assignment.HeadPartFormKeys is { Count: > 0 } parts)
        {
            npcOverride.HeadParts.Clear();
            foreach (var p in parts)
            {
                if (queries.TryParseAnyFormKey(p, out var hpKey))
                {
                    npcOverride.HeadParts.Add(new FormLink<IHeadPartGetter>(hpKey));
                }
                else
                {
                    issues.Add(Issue.Warning("InvalidHeadPartKey", $"HeadPart FormKey '{p}' could not be parsed."));
                }
            }
        }

        // 3. Skin tone
        if (assignment.SkinTone is { } st)
        {
            npcOverride.TextureLighting = System.Drawing.Color.FromArgb(st.R, st.G, st.B);
        }

        // 4. Morphs
        if (assignment.FaceMorphs is { } fm)
        {
            npcOverride.FaceMorph ??= new NpcFaceMorph();
            npcOverride.FaceMorph.NoseLongVsShort = fm.NoseLongVsShort;
            npcOverride.FaceMorph.NoseUpVsDown = fm.NoseUpVsDown;
            npcOverride.FaceMorph.JawUpVsDown = fm.JawUpVsDown;
            npcOverride.FaceMorph.JawNarrowVsWide = fm.JawNarrowVsWide;
            npcOverride.FaceMorph.JawForwardVsBack = fm.JawForwardVsBack;
            npcOverride.FaceMorph.CheeksUpVsDown = fm.CheeksUpVsDown;
            npcOverride.FaceMorph.CheeksForwardVsBack = fm.CheeksForwardVsBack;
            npcOverride.FaceMorph.EyesUpVsDown = fm.EyesUpVsDown;
            npcOverride.FaceMorph.EyesInVsOut = fm.EyesInVsOut;
            npcOverride.FaceMorph.EyesForwardVsBack = fm.EyesForwardVsBack;
            npcOverride.FaceMorph.BrowsUpVsDown = fm.BrowsUpVsDown;
            npcOverride.FaceMorph.BrowsInVsOut = fm.BrowsInVsOut;
            npcOverride.FaceMorph.BrowsForwardVsBack = fm.BrowsForwardVsBack;
            npcOverride.FaceMorph.LipsUpVsDown = fm.LipsUpVsDown;
            npcOverride.FaceMorph.LipsInVsOut = fm.LipsInVsOut;
            npcOverride.FaceMorph.ChinNarrowVsWide = fm.ChinNarrowVsWide;
            npcOverride.FaceMorph.ChinUpVsDown = fm.ChinUpVsDown;
            npcOverride.FaceMorph.ChinUnderbiteVsOverbite = fm.ChinUnderbiteVsOverbite;
        }

        // 5. Face parts
        if (assignment.FaceParts is { } fp)
        {
            npcOverride.FaceParts = new NpcFaceParts { Nose = fp.Nose, Eyes = fp.Eyes, Mouth = fp.Mouth };
        }

        // 6. Tints
        if (assignment.TintLayers is { } tints)
        {
            npcOverride.TintLayers.Clear();
            foreach (var t in tints)
            {
                npcOverride.TintLayers.Add(new TintLayer
                {
                    Index = (ushort)t.Index,
                    Color = System.Drawing.Color.FromArgb(t.Color.R, t.Color.G, t.Color.B),
                    InterpolationValue = t.Alpha,
                    Preset = (short)t.Preset,
                });
            }
        }

        // 7. Weight & Height
        if (assignment.Weight.HasValue) npcOverride.Weight = assignment.Weight.Value;
        if (assignment.Height.HasValue) npcOverride.Height = assignment.Height.Value;
    }

    private static void StageFaceGenFiles(
        LoadOrderSession session, CatalogQueries queries, FaceAssignment assignment, FormKey targetKey,
        string stagedModDir, List<Issue> issues)
    {
        var targetFaceGen = CatalogQueries.FaceGenFor(targetKey);
        var targetNifDest = Path.Combine(stagedModDir, targetFaceGen.GeometryPath);
        var targetDdsDest = Path.Combine(stagedModDir, targetFaceGen.TintPath);

        // Find source NIF
        string? sourceNif = null;
        if (!string.IsNullOrWhiteSpace(assignment.DonorFaceGeometryPath))
        {
            sourceNif = ResolveFilePath(assignment.DonorFaceGeometryPath, session);
        }
        else if (!string.IsNullOrWhiteSpace(assignment.DonorNpcFormKey)
            && queries.TryParseAnyFormKey(assignment.DonorNpcFormKey, out var donorKey))
        {
            var donorFaceGen = CatalogQueries.FaceGenFor(donorKey);
            sourceNif = ResolveFilePath(donorFaceGen.GeometryPath, session);
        }

        // Find source DDS
        string? sourceDds = null;
        if (!string.IsNullOrWhiteSpace(assignment.DonorFaceTintPath))
        {
            sourceDds = ResolveFilePath(assignment.DonorFaceTintPath, session);
        }
        else if (!string.IsNullOrWhiteSpace(assignment.DonorNpcFormKey)
            && queries.TryParseAnyFormKey(assignment.DonorNpcFormKey, out var donorKey))
        {
            var donorFaceGen = CatalogQueries.FaceGenFor(donorKey);
            sourceDds = ResolveFilePath(donorFaceGen.TintPath, session);
        }

        if (sourceNif is not null && File.Exists(sourceNif))
        {
            Directory.CreateDirectory(Path.GetDirectoryName(targetNifDest)!);
            File.Copy(sourceNif, targetNifDest, overwrite: true);
        }
        else if (sourceNif is not null)
        {
            issues.Add(Issue.Warning("FaceGenMissing", $"Source FaceGen mesh not found: '{sourceNif}'."));
        }

        if (sourceDds is not null && File.Exists(sourceDds))
        {
            Directory.CreateDirectory(Path.GetDirectoryName(targetDdsDest)!);
            File.Copy(sourceDds, targetDdsDest, overwrite: true);
        }
        else if (sourceDds is not null)
        {
            issues.Add(Issue.Warning("FaceGenMissing", $"Source FaceGen tint texture not found: '{sourceDds}'."));
        }
    }

    private static string? ResolveFilePath(string candidate, LoadOrderSession session)
    {
        if (string.IsNullOrWhiteSpace(candidate)) return null;
        if (Path.IsPathRooted(candidate) && File.Exists(candidate)) return candidate;

        foreach (var p in session.Plugins)
        {
            var dir = Path.GetDirectoryName(p.Path);
            if (!string.IsNullOrEmpty(dir))
            {
                var full = Path.Combine(dir, candidate);
                if (File.Exists(full)) return full;
            }
        }

        return candidate;
    }

    private static IReadOnlyList<ModKey> Verify(
        LoadOrderSession session, string pluginPath, ModKey patchKey, int expectedCount, bool esl, List<Issue> issues)
    {
        using var written = SkyrimMod.CreateFromBinaryOverlay(
            new ModPath(patchKey, pluginPath), SkyrimRelease.SkyrimSE,
            new BinaryReadParameters { MasterFlagsLookup = session.MasterStyles });

        var masters = written.ModHeader.MasterReferences.Select(m => m.Master).ToList();
        var lastIndex = -1;
        foreach (var master in masters)
        {
            var plugin = session.Find(master)
                ?? throw new WorkerException(ErrorCodes.ValidationFailed, $"Verification failed: master '{master}' is not in the load order.");
            if (plugin.LoadIndex < lastIndex)
            {
                throw new WorkerException(ErrorCodes.ValidationFailed, "Verification failed: masters are not in load order.");
            }

            lastIndex = plugin.LoadIndex;
        }

        if (esl != written.ModHeader.Flags.HasFlag(SkyrimModHeader.HeaderFlag.Small))
        {
            throw new WorkerException(ErrorCodes.ValidationFailed, "Verification failed: ESL flag mismatch after writing.");
        }

        var npcs = written.Npcs.ToDictionary(n => n.FormKey);
        if (npcs.Count != expectedCount)
        {
            throw new WorkerException(ErrorCodes.ValidationFailed,
                $"Verification failed: expected {expectedCount} NPC overrides, found {npcs.Count}.");
        }

        foreach (var record in written.EnumerateMajorRecords())
        {
            foreach (var link in record.EnumerateFormLinks())
            {
                if (link.IsNull || link.FormKey.ModKey == patchKey)
                {
                    continue;
                }

                if (!session.LinkCache.TryResolve(link.FormKey, link.Type, out _))
                {
                    issues.Add(Issue.Warning("UnresolvedReference",
                        $"{record.FormKey} references {link.FormKey}, which does not resolve in active load order.",
                        record.FormKey.ToString()));
                }
            }
        }

        return masters;
    }

    private static string UniqueEditorId(string candidate, HashSet<string> used)
    {
        var baseId = Regex.Replace(candidate, @"[^A-Za-z0-9_]", "_");
        if (baseId.Length > 90) baseId = baseId[..90];
        var id = baseId;
        for (var n = 2; !used.Add(id); n++)
        {
            id = $"{baseId}{n}";
        }
        return id;
    }

    private static string Truncate(string value, int max) => value.Length <= max ? value : value[..max];
}
