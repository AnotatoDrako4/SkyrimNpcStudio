/// <summary>
/// Modes B (face overhaul) and C (complete overhaul: face + outfit in one plugin).
///
/// The NPC override is a copy of the WINNING record with the face fields replaced by the complete
/// values the studio edited (NAM9, NAMA, PNAM, FTST, QNAM, HCLF, tints, weight, height). The FaceGen
/// files are NOT copied from any mod: the studio regenerates them (engines/face) and sends them as
/// generated assets, which are checked here (destination, hash) before they enter the mod. If the
/// record changes something the FaceGen depends on and no regenerated file comes with it, the export
/// is refused: the game would show the old FaceGen (or a dark face) instead of the edit.
/// </summary>
internal static partial class FacePatchBuilder
{
    public const uint LightRangeMin = 0x800;
    public const uint LightRangeMax = 0xFFF;

    public static BuiltPatch BuildFaceOverhaul(
        LoadOrderSession session, CatalogQueries queries, ExportFaceOverhaulRequest request,
        string stagedPluginPath, string stagedModDir, CancellationToken ct)
    {
        if (request.Assignments.Count == 0)
        {
            throw new WorkerException(ErrorCodes.InvalidArgument, "At least one face assignment is required.");
        }

        return Build(session, queries, request.PluginName, request.Author,
            request.Description ?? "Generated by Skyrim NPC Studio (Face Overhaul)", request.EslFlag,
            request.Assignments.Select(a => new CompleteNpcAssignment { NpcFormKey = a.NpcFormKey, Face = a }).ToList(),
            request.PluginProviders, stagedPluginPath, stagedModDir, ct);
    }

    public static BuiltPatch BuildCompleteOverhaul(
        LoadOrderSession session, CatalogQueries queries, ExportCompleteOverhaulRequest request,
        string stagedPluginPath, string stagedModDir, CancellationToken ct)
    {
        if (request.Assignments.Count == 0)
        {
            throw new WorkerException(ErrorCodes.InvalidArgument, "At least one complete NPC assignment is required.");
        }

        return Build(session, queries, request.PluginName, request.Author,
            request.Description ?? "Generated by Skyrim NPC Studio (Complete Overhaul)", request.EslFlag,
            request.Assignments, request.PluginProviders, stagedPluginPath, stagedModDir, ct);
    }

    private static BuiltPatch Build(
        LoadOrderSession session, CatalogQueries queries, string pluginName, string author, string description, bool esl,
        IReadOnlyList<CompleteNpcAssignment> assignments, IReadOnlyDictionary<string, string>? providers,
        string stagedPluginPath, string stagedModDir, CancellationToken ct)
    {
        OutfitPatchBuilder.ValidatePluginName(pluginName, session);
        var issues = new List<Issue>();
        var patchKey = ModKey.FromFileName(pluginName);
        var patch = new SkyrimMod(patchKey, SkyrimRelease.SkyrimSE);
        patch.ModHeader.Author = Truncate(author, 255);
        patch.ModHeader.Description = Truncate(description, 511);
        if (esl)
        {
            patch.ModHeader.Flags |= SkyrimModHeader.HeaderFlag.Small;
        }

        var records = new List<ExportedRecord>();
        var built = new List<BuiltAssignment>();
        var generated = new List<BuiltGeneratedAsset>();
        var faces = new List<BuiltFace>();
        var expectations = new List<(FormKey Npc, FaceAssignment Face, FormKey? HairColor)>();
        var npcsSeen = new HashSet<FormKey>();
        var allowedByNpc = new Dictionary<FormKey, IReadOnlySet<string>>();
        var usedEditorIds = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        // Plugins the patch must load after although none of its links points at them: for a face copied
        // from another version, the source and the winning plugin (declared as masters).
        var loadAfter = new HashSet<ModKey>();
        var projected = new List<FormKey>();

        foreach (var item in assignments)
        {
            ct.ThrowIfCancellationRequested();
            if (!queries.TryParseAnyFormKey(item.NpcFormKey, out var npcKey)
                || !session.LinkCache.TryResolve<INpcGetter>(npcKey, out var winner))
            {
                issues.Add(Issue.Error("TargetNpcNotFound", $"Target NPC not found in active load order: '{item.NpcFormKey}'."));
                continue;
            }

            if (!npcsSeen.Add(npcKey))
            {
                issues.Add(Issue.Error("DuplicateNpc", "The same NPC has two assignments in one patch.", npcKey.ToString()));
                continue;
            }

            if (item.Face is null && item.Outfit is null)
            {
                issues.Add(Issue.Error("EmptyAssignment", "Nothing to export for this NPC (no face, no outfit).", npcKey.ToString()));
                continue;
            }

            var npc = patch.Npcs.GetOrAddAsOverride(winner);
            // What this NPC's override may differ in from the winning record; Verify proves it.
            allowedByNpc[npcKey] = NpcSafePatch.Union(
                item.Face is { } faceRequest ? NpcSafePatch.AllowedForFace(faceRequest) : null,
                item.Outfit is { ArmorFormKeys.Count: > 0 } outfitRequest ? NpcSafePatch.AllowedForOutfit(outfitRequest.AlsoSetSleepingOutfit) : null);
            FormKey outfitKey = FormKey.Null;
            var outfitEditorId = "";
            var pieces = new List<ArmorSummary>();

            if (item.Outfit is { } outfitAssignment && outfitAssignment.ArmorFormKeys.Count > 0)
            {
                var validation = OutfitValidator.Validate(session, queries, new OutfitValidateRequest
                {
                    NpcFormKey = outfitAssignment.NpcFormKey,
                    ArmorFormKeys = outfitAssignment.ArmorFormKeys,
                });
                issues.AddRange(validation.Issues.Where(i => i.Code != "SaveGamePersistence"));
                if (validation.Exportable)
                {
                    outfitEditorId = UniqueEditorId(outfitAssignment.OutfitEditorId ?? $"SNS_{winner.EditorID ?? winner.FormKey.ID.ToString("X6")}Outfit", usedEditorIds);
                    var outfit = patch.Outfits.AddNew(outfitEditorId);
                    var (itemKeys, outfitPieces) = OutfitPatchBuilder.ResolveOutfitItems(validation.Pieces, outfitAssignment.MaterialOverrides);
                    outfit.Items = new ExtendedList<IFormLinkGetter<IOutfitTargetGetter>>(
                        itemKeys.Select(k => (IFormLinkGetter<IOutfitTargetGetter>)new FormLink<IOutfitTargetGetter>(k)));
                    outfitKey = outfit.FormKey;
                    npc.DefaultOutfit.SetTo(outfitKey);
                    if (outfitAssignment.AlsoSetSleepingOutfit)
                    {
                        npc.SleepingOutfit.SetTo(outfitKey);
                    }

                    records.Add(new ExportedRecord { FormKey = outfitKey.ToString(), RecordType = "OTFT", EditorId = outfitEditorId, Kind = "new" });
                    pieces.AddRange(outfitPieces);
                }
            }

            if (item.Face is { } face)
            {
                var hair = face.CopyFaceFrom is { } source
                    ? ApplySourceFace(session, face, source, winner, npc, providers, loadAfter, issues)
                    : face.OnlyFields is { } only
                    ? ApplyOnlyFields(session, face, only, winner, npc, patch, usedEditorIds, records, issues)
                    : ApplyFace(session, queries, face, winner, npc, patch, usedEditorIds, records, issues);
                var changed = ChangedFields(winner, npc);
                if (face.OnlyFields is { } allowed && changed.Except(allowed, StringComparer.Ordinal).ToList() is { Count: > 0 } extra)
                {
                    issues.Add(Issue.Error("MinimalChangeViolated",
                        $"The export may only change {string.Join(", ", allowed)} but {string.Join(", ", extra)} also differ from the winning record.",
                        npcKey.ToString()));
                }
                if (face.CopyFaceFrom is not null)
                {
                    projected.Add(npcKey);
                }
                else
                {
                    StageGeneratedAssets(npcKey, face, changed, stagedModDir, generated, issues);
                }
                expectations.Add((npcKey, face, hair));
                faces.Add(new BuiltFace(npcKey.ToString(), winner.EditorID, face.FaceGen ?? new FaceGenProvenance(), changed));
            }

            records.Add(new ExportedRecord { FormKey = winner.FormKey.ToString(), RecordType = "NPC_", EditorId = winner.EditorID, Kind = "override" });
            built.Add(new BuiltAssignment(winner.FormKey, winner.EditorID, winner.Name?.String, outfitKey, outfitEditorId, pieces));
        }

        if (issues.Any(i => i.Severity == "error"))
        {
            throw new WorkerException(ErrorCodes.ValidationFailed, "Validation failed; nothing was written.", issues);
        }

        // Same note as an outfit-only patch: a new DefaultOutfit does not re-equip NPCs a save already holds.
        if (built.Any(b => !b.Outfit.IsNull))
        {
            issues.Add(Issue.Info("SaveGamePersistence",
                "NPCs already loaded in an existing save can keep their current equipment until the game re-initializes them; immediate application in every save is not guaranteed."));
        }

        if (esl)
        {
            foreach (var record in patch.EnumerateMajorRecords().Where(r => r.FormKey.ModKey == patchKey))
            {
                if (record.FormKey.ID is < LightRangeMin or > LightRangeMax)
                {
                    throw new WorkerException(ErrorCodes.ValidationFailed,
                        $"ESL flag rejected: new record {record.FormKey} is outside the light-plugin range 0x800–0xFFF.");
                }
            }
        }

        var loadOrderKeys = session.Plugins.Select(p => p.ModKey).ToArray();
        patch.WriteToBinary(stagedPluginPath, new BinaryWriteParameters
        {
            MastersListOrdering = new MastersListOrderingByLoadOrder(loadOrderKeys),
            MasterFlagsLookup = session.MasterStyles,
            MastersContentCustomOverride = found => found.Union(loadAfter).ToArray(),
        });

        var masters = Verify(session, queries, stagedPluginPath, patchKey, built.Count, esl, expectations, allowedByNpc,
            out var semanticDiffs, issues);
        var missingMasters = loadAfter.Except(masters).ToList();
        if (missingMasters.Count > 0)
        {
            throw new WorkerException(ErrorCodes.ValidationFailed,
                $"Verification failed: the plugin does not declare {string.Join(", ", missingMasters)} as masters; it would not load after them.");
        }

        var chains = ProjectChains(session, queries, stagedPluginPath, patchKey, pluginName, projected);
        foreach (var asset in generated)
        {
            var staged = Path.Combine(stagedModDir, asset.DataPath);
            if (!string.Equals(Sha256Of(staged), asset.Sha256, StringComparison.OrdinalIgnoreCase))
            {
                throw new WorkerException(ErrorCodes.ValidationFailed, $"Verification failed: staged '{asset.DataPath}' changed while exporting.");
            }
        }

        return new BuiltPatch(stagedPluginPath, masters, esl, records, built, issues, generated, faces, SemanticDiffs: semanticDiffs,
            ProjectedChains: chains, LoadAfter: loadAfter.Select(k => k.FileName.String).ToArray());
    }

    /// <summary>Subrecords a face copied from another version may write (FaceAssignment.CopyFaceFrom).</summary>
    public static readonly IReadOnlyList<string> SourceFaceFields = ["PNAM", "NAM9", "NAMA", "TINT", "HCLF", "FTST", "QNAM", "NAM7"];

    /// <summary>
    /// Assisted resolution: copies the OnlyFields face subrecords of <paramref name="sourcePlugin"/>'s
    /// version of the record onto the override of the winner, verbatim (links, morphs, tints). The source
    /// must be an earlier version of the same race and sex whose mod provides the FaceGen the game already
    /// uses; no FaceGen may come with it. Returns the HCLF it points to.
    /// </summary>
    private static FormKey? ApplySourceFace(
        LoadOrderSession session, FaceAssignment face, string sourcePlugin, INpcGetter winner, Npc npc,
        IReadOnlyDictionary<string, string>? providers, HashSet<ModKey> loadAfter, List<Issue> issues)
    {
        var subject = winner.FormKey.ToString();
        var only = face.OnlyFields ?? [];
        if (only.Count == 0)
        {
            issues.Add(Issue.Error("CopyFaceFieldsRequired", "A face copied from another plugin needs the fields to copy (OnlyFields).", subject));
        }

        if (only.Where(f => !SourceFaceFields.Contains(f)).ToList() is { Count: > 0 } unknown)
        {
            issues.Add(Issue.Error("OnlyFieldsUnsupported",
                $"A face copied from another plugin cannot write {string.Join(", ", unknown)}; only {string.Join(", ", SourceFaceFields)}.", subject));
        }

        if (face.GeneratedAssets is { Count: > 0 })
        {
            issues.Add(Issue.Error("SourceFaceGenNoAssets",
                "A face copied from another plugin keeps that mod's FaceGen: no generated FaceGen may come with it.", subject));
        }

        if (face.FaceGen?.Mode != "source-facegen")
        {
            issues.Add(Issue.Error("SourceFaceGenModeRequired", "A face copied from another plugin must declare FaceGen mode 'source-facegen'.", subject));
        }

        var plugin = ModKey.TryFromFileName(sourcePlugin, out var sourceKey) ? session.Find(sourceKey) : null;
        if (plugin is null)
        {
            issues.Add(Issue.Error("FaceSourceNotFound", $"Plugin '{sourcePlugin}' is not in the active load order.", subject));
            return npc.HairColor.FormKeyNullable;
        }

        if (!plugin.Mod.Npcs.RecordCache.TryGetValue(winner.FormKey, out var source))
        {
            issues.Add(Issue.Error("FaceSourceNoRecord", $"'{sourcePlugin}' does not contain {winner.EditorID ?? subject}.", subject));
            return npc.HairColor.FormKeyNullable;
        }

        var winning = session.LinkCache.ResolveContext<INpc, INpcGetter>(winner.FormKey).ModKey;
        if (winning == sourceKey)
        {
            issues.Add(Issue.Error("FaceSourceIsWinner", $"'{sourcePlugin}' already wins the record: there is nothing to copy.", subject));
        }

        // The FaceGen was built for the source's race and sex; those are never copied.
        if (source.Race.FormKey != winner.Race.FormKey
            || source.Configuration.Flags.HasFlag(NpcConfiguration.Flag.Female) != winner.Configuration.Flags.HasFlag(NpcConfiguration.Flag.Female))
        {
            issues.Add(Issue.Error("FaceSourceRaceMismatch",
                $"'{sourcePlugin}' gives {winner.EditorID ?? subject} another race or sex than the winning record; copying its face alone would not fit.", subject));
        }

        // The studio located the effective FaceGen in MO2; it must belong to the mod that provides the source.
        var faceGenMod = face.FaceGen?.EffectiveFaceGenMod;
        if (string.IsNullOrEmpty(faceGenMod))
        {
            issues.Add(Issue.Error("FaceSourceFaceGenUnknown", "The mod of the FaceGen the game uses was not given (FaceGen.EffectiveFaceGenMod).", subject));
        }
        else if (providers?.GetValueOrDefault(sourcePlugin) is { } provider && !string.Equals(provider, faceGenMod, StringComparison.OrdinalIgnoreCase))
        {
            issues.Add(Issue.Error("FaceSourceNotFaceGenMod",
                $"'{sourcePlugin}' comes from «{provider}» but the FaceGen the game uses comes from «{faceGenMod}»: the copied face would not match it.", subject));
        }

        if (only.Contains("PNAM"))
        {
            npc.HeadParts.Clear();
            npc.HeadParts.AddRange(source.HeadParts.Select(h => new FormLink<IHeadPartGetter>(h.FormKey)));
        }

        if (only.Contains("NAM9")) npc.FaceMorph = source.FaceMorph?.DeepCopy();
        if (only.Contains("NAMA")) npc.FaceParts = source.FaceParts?.DeepCopy();
        if (only.Contains("TINT"))
        {
            npc.TintLayers.Clear();
            npc.TintLayers.AddRange(source.TintLayers.Select(t => t.DeepCopy()));
        }

        if (only.Contains("HCLF")) npc.HairColor.SetTo(source.HairColor.FormKeyNullable);
        if (only.Contains("FTST")) npc.HeadTexture.SetTo(source.HeadTexture.FormKeyNullable);
        if (only.Contains("QNAM")) npc.TextureLighting = source.TextureLighting;
        if (only.Contains("NAM7")) npc.Weight = source.Weight;

        loadAfter.Add(sourceKey);
        loadAfter.Add(winning);
        return npc.HairColor.FormKeyNullable;
    }

    /// <summary>Each NPC's override chain with the written plugin loaded last, from the re-read file.</summary>
    private static IReadOnlyList<ProjectedChain> ProjectChains(
        LoadOrderSession session, CatalogQueries queries, string pluginPath, ModKey patchKey, string pluginName, IReadOnlyList<FormKey> npcs)
    {
        if (npcs.Count == 0)
        {
            return [];
        }

        using var written = SkyrimMod.CreateFromBinaryOverlay(
            new ModPath(patchKey, pluginPath), SkyrimRelease.SkyrimSE,
            new BinaryReadParameters { MasterFlagsLookup = session.MasterStyles });
        var chains = new List<ProjectedChain>();
        foreach (var key in npcs)
        {
            if (!written.Npcs.RecordCache.TryGetValue(key, out var npc))
            {
                throw new WorkerException(ErrorCodes.ValidationFailed, $"Verification failed: {key} missing from the plugin.");
            }

            // The name is the winner's: the safe patch proved the text the game shows is the same, and the
            // catalog stores the fingerprint of that resolved text (string tables included).
            var fingerprints = RecordExtractor.Fingerprints(npc, null);
            if (queries.WinnerFingerprints(key)?.GetValueOrDefault("Name") is { } name)
            {
                fingerprints["Name"] = name;
            }

            chains.Add(queries.ProjectChain(key, pluginName, fingerprints));
        }

        return chains;
    }

    /// <summary>
    /// Minimal change: the override keeps the winning record as copied and only the listed fields are
    /// written (HCLF from Values.HairColor, NAM6 from Height). Returns the HCLF it points to.
    /// </summary>
    private static FormKey? ApplyOnlyFields(
        LoadOrderSession session, FaceAssignment face, IReadOnlyList<string> only, INpcGetter winner, Npc npc,
        SkyrimMod patch, HashSet<string> usedEditorIds, List<ExportedRecord> records, List<Issue> issues)
    {
        var subject = winner.FormKey.ToString();
        var unknown = only.Where(f => f is not ("HCLF" or "NAM6")).ToList();
        if (unknown.Count > 0)
        {
            issues.Add(Issue.Error("OnlyFieldsUnsupported", $"Minimal export cannot write {string.Join(", ", unknown)}.", subject));
        }

        if (only.Contains("NAM6"))
        {
            if (face.Height is { } height)
            {
                npc.Height = Math.Clamp(height, 0.5f, 2.0f);
            }
            else
            {
                issues.Add(Issue.Error("FaceValuesInvalid", "NAM6 was requested without a height.", subject));
            }
        }

        if (!only.Contains("HCLF"))
        {
            return npc.HairColor.FormKeyNullable;
        }

        if (face.Values is null)
        {
            issues.Add(Issue.Error("FaceValuesInvalid", "HCLF was requested without face values.", subject));
            return npc.HairColor.FormKeyNullable;
        }

        return SetHairColor(session, face.Values.HairColor, winner, npc, patch, usedEditorIds, records);
    }

    /// <summary>Writes the complete face values into the override. Returns the HCLF it points to.</summary>
    private static FormKey? ApplyFace(
        LoadOrderSession session, CatalogQueries queries, FaceAssignment face, INpcGetter winner, Npc npc,
        SkyrimMod patch, HashSet<string> usedEditorIds, List<ExportedRecord> records, List<Issue> issues)
    {
        var subject = winner.FormKey.ToString();
        // Only what the user changed is written (RequestedFields); the rest stays the winner's copy.
        bool Want(string field) => face.RequestedFields is not { } requested || requested.Contains(field);
        if (face.Values is { } v)
        {
            if (v.Sliders.Count != 18 || v.Presets.Count != 4)
            {
                issues.Add(Issue.Error("FaceValuesInvalid", "Face values need 18 sliders and 4 presets.", subject));
                return null;
            }

            if (Want("FaceMorph"))
            {
            var fm = npc.FaceMorph ?? new NpcFaceMorph();
            float S(int i) => Math.Clamp(float.IsFinite(v.Sliders[i]) ? v.Sliders[i] : 0f, -1f, 1f);
            fm.NoseLongVsShort = S(0);
            fm.NoseUpVsDown = S(1);
            fm.JawUpVsDown = S(2);
            fm.JawNarrowVsWide = S(3);
            fm.JawForwardVsBack = S(4);
            fm.CheeksUpVsDown = S(5);
            fm.CheeksForwardVsBack = S(6);
            fm.EyesUpVsDown = S(7);
            fm.EyesInVsOut = S(8);
            fm.BrowsUpVsDown = S(9);
            fm.BrowsInVsOut = S(10);
            fm.BrowsForwardVsBack = S(11);
            fm.LipsUpVsDown = S(12);
            fm.LipsInVsOut = S(13);
            fm.ChinNarrowVsWide = S(14);
            fm.ChinUpVsDown = S(15);
            fm.ChinUnderbiteVsOverbite = S(16);
            fm.EyesForwardVsBack = S(17);
            npc.FaceMorph = fm;
            }
            if (Want("FaceParts")) npc.FaceParts = new NpcFaceParts
            {
                Nose = unchecked((uint)v.Presets[0]),
                Unknown = unchecked((uint)v.Presets[1]),
                Eyes = unchecked((uint)v.Presets[2]),
                Mouth = unchecked((uint)v.Presets[3]),
            };
            if (Want("Weight")) npc.Weight = Math.Clamp(v.Weight, 0f, 100f);
            // QNAM is stored as RGB: the alpha Mutagen reports is not data. Keep the record's value so
            // an unchanged skin tone stays byte-identical.
            // A record without QNAM is read as white (FaceRecipeQueries): leave it without QNAM unless
            // the tone was really changed.
            var untouchedDefault = winner.TextureLighting is null && v.SkinTone.R == 255 && v.SkinTone.G == 255 && v.SkinTone.B == 255;
            if (Want("TextureLighting")) npc.TextureLighting = untouchedDefault
                ? null
                : System.Drawing.Color.FromArgb(winner.TextureLighting?.A ?? 255, v.SkinTone.R, v.SkinTone.G, v.SkinTone.B);
            if (Want("TintLayers")) npc.TintLayers.Clear();
            foreach (var t in Want("TintLayers") ? v.Tints : [])
            {
                npc.TintLayers.Add(new TintLayer
                {
                    Index = (ushort)t.Index,
                    // Vanilla TINC stores alpha 0; the game only uses the color channels.
                    Color = System.Drawing.Color.FromArgb(0, t.Color.R, t.Color.G, t.Color.B),
                    InterpolationValue = Math.Clamp(t.Value, 0f, 1f),
                    Preset = (short)Math.Clamp(t.Preset, short.MinValue, short.MaxValue),
                });
            }
        }

        if (face.HeadParts is { } parts && Want("HeadParts"))
        {
            npc.HeadParts.Clear();
            foreach (var text in parts)
            {
                if (queries.TryParseAnyFormKey(text, out var key) && session.LinkCache.TryResolve<IHeadPartGetter>(key, out _))
                {
                    npc.HeadParts.Add(new FormLink<IHeadPartGetter>(key));
                }
                else
                {
                    issues.Add(Issue.Error("HeadPartUnresolved", $"Head part '{text}' does not resolve in the active load order.", subject));
                }
            }
        }

        if (face.HeadTexture is { } texture && Want("HeadTexture"))
        {
            if (texture.Length == 0)
            {
                npc.HeadTexture.Clear();
            }
            else if (queries.TryParseAnyFormKey(texture, out var tk) && session.LinkCache.TryResolve<ITextureSetGetter>(tk, out _))
            {
                npc.HeadTexture.SetTo(tk);
            }
            else
            {
                issues.Add(Issue.Error("HeadTextureUnresolved", $"Face texture set '{texture}' does not resolve.", subject));
            }
        }

        if (face.Height is { } height && Want("Height"))
        {
            npc.Height = Math.Clamp(height, 0.5f, 2.0f);
        }

        return face.Values is { } values && Want("HairColor")
            ? SetHairColor(session, values.HairColor, winner, npc, patch, usedEditorIds, records)
            : npc.HairColor.FormKeyNullable;
    }

    /// <summary>
    /// HCLF: keep the record's CLFM when the color is unchanged, reuse an existing CLFM with exactly
    /// that color, otherwise add a new color record to the patch. Null clears it.
    /// </summary>
    private static FormKey? SetHairColor(
        LoadOrderSession session, AppearanceColor? wanted, INpcGetter winner, Npc npc, SkyrimMod patch,
        HashSet<string> usedEditorIds, List<ExportedRecord> records)
    {
        FormKey? hair = npc.HairColor.FormKeyNullable;
        if (wanted is null)
        {
            npc.HairColor.Clear();
            return null;
        }

        bool Same(IColorRecordGetter c) => c.Color.R == wanted.R && c.Color.G == wanted.G && c.Color.B == wanted.B;
        if (hair is { } current && session.LinkCache.TryResolve<IColorRecordGetter>(current, out var currentColor) && Same(currentColor))
        {
            return hair;
        }

        if (session.LinkCache.PriorityOrder.WinningOverrides<IColorRecordGetter>().FirstOrDefault(Same) is { } existing)
        {
            npc.HairColor.SetTo(existing.FormKey);
            return existing.FormKey;
        }

        var editorId = UniqueEditorId($"SNS_HairColor_{winner.EditorID ?? winner.FormKey.ID.ToString("X6")}", usedEditorIds);
        var color = patch.Colors.AddNew(editorId);
        color.Color = System.Drawing.Color.FromArgb(255, wanted.R, wanted.G, wanted.B);
        color.Playable = true;
        npc.HairColor.SetTo(color.FormKey);
        records.Add(new ExportedRecord { FormKey = color.FormKey.ToString(), RecordType = "CLFM", EditorId = editorId, Kind = "new" });
        return color.FormKey;
    }

    /// <summary>Face fields of the override that differ from the winning record.</summary>
    private static IReadOnlyList<string> ChangedFields(INpcGetter winner, INpcGetter npc)
    {
        var changed = new List<string>();
        if (!FaceRecipeQueries.Sliders(winner.FaceMorph).SequenceEqual(FaceRecipeQueries.Sliders(npc.FaceMorph))) changed.Add("NAM9");
        if (!Equals(winner.FaceParts?.Nose, npc.FaceParts?.Nose) || !Equals(winner.FaceParts?.Eyes, npc.FaceParts?.Eyes)
            || !Equals(winner.FaceParts?.Mouth, npc.FaceParts?.Mouth)) changed.Add("NAMA");
        if (!winner.HeadParts.Select(h => h.FormKey).SequenceEqual(npc.HeadParts.Select(h => h.FormKey))) changed.Add("PNAM");
        if (winner.HeadTexture.FormKeyNullable != npc.HeadTexture.FormKeyNullable) changed.Add("FTST");
        if (winner.Weight != npc.Weight) changed.Add("NAM7");
        if (winner.Height != npc.Height) changed.Add("NAM6");
        if (winner.HairColor.FormKeyNullable != npc.HairColor.FormKeyNullable) changed.Add("HCLF");
        // Only the color channels exist in the file (see ApplyFace).
        if ((winner.TextureLighting?.R, winner.TextureLighting?.G, winner.TextureLighting?.B)
            != (npc.TextureLighting?.R, npc.TextureLighting?.G, npc.TextureLighting?.B)) changed.Add("QNAM");
        var a = winner.TintLayers.Select(t => (t.Index, t.Color?.R, t.Color?.G, t.Color?.B, t.InterpolationValue)).ToList();
        var b = npc.TintLayers.Select(t => (t.Index, t.Color?.R, t.Color?.G, t.Color?.B, t.InterpolationValue)).ToList();
        if (!a.SequenceEqual(b)) changed.Add("TINT");
        return changed;
    }

    private static void StageGeneratedAssets(
        FormKey npcKey, FaceAssignment face, IReadOnlyList<string> changed, string stagedModDir,
        List<BuiltGeneratedAsset> generated, List<Issue> issues)
    {
        var expected = CatalogQueries.FaceGenFor(npcKey);
        var subject = npcKey.ToString();
        bool geometry = false, tint = false;
        foreach (var asset in face.GeneratedAssets ?? [])
        {
            var dataPath = asset.DataPath.Replace('/', '\\').TrimStart('\\');
            var isGeometry = string.Equals(dataPath, expected.GeometryPath, StringComparison.OrdinalIgnoreCase) && asset.Kind == "facegen-geometry";
            var isTint = string.Equals(dataPath, expected.TintPath, StringComparison.OrdinalIgnoreCase) && asset.Kind == "facegen-tint";
            if (!isGeometry && !isTint)
            {
                issues.Add(Issue.Error("GeneratedAssetRejected",
                    $"'{asset.DataPath}' ({asset.Kind}) is not this NPC's FaceGen path; only {expected.GeometryPath} and {expected.TintPath} are accepted.", subject));
                continue;
            }

            if (!Path.IsPathFullyQualified(asset.SourcePath) || !File.Exists(asset.SourcePath))
            {
                issues.Add(Issue.Error("GeneratedAssetMissing", $"Generated file not found: '{asset.SourcePath}'.", subject));
                continue;
            }

            var hash = Sha256Of(asset.SourcePath);
            if (!string.Equals(hash, asset.Sha256, StringComparison.OrdinalIgnoreCase))
            {
                issues.Add(Issue.Error("GeneratedAssetHashMismatch", $"'{asset.DataPath}' does not match the hash the studio sent.", subject));
                continue;
            }

            var destination = Path.Combine(stagedModDir, isGeometry ? expected.GeometryPath : expected.TintPath);
            Directory.CreateDirectory(Path.GetDirectoryName(destination)!);
            File.Copy(asset.SourcePath, destination, overwrite: false);
            generated.Add(new BuiltGeneratedAsset(subject, isGeometry ? expected.GeometryPath : expected.TintPath, hash, asset.Kind));
            geometry |= isGeometry;
            tint |= isTint;
        }

        // The game draws the FaceGen file, not the record: record edits that change the head must come
        // with the regenerated head, or the export would only look edited in the studio.
        var geometryFields = changed.Intersect(["NAM9", "NAMA", "PNAM", "FTST", "NAM7", "HCLF"]).ToList();
        if (geometryFields.Count > 0 && !geometry)
        {
            issues.Add(Issue.Error("FaceGenRequired",
                $"The export changes {string.Join(", ", geometryFields)} but has no regenerated FaceGen NIF; the game would keep showing the old head.", subject));
        }

        var tintFields = changed.Intersect(["QNAM", "TINT"]).ToList();
        if (tintFields.Count > 0 && !tint)
        {
            issues.Add(Issue.Error("FaceTintRequired",
                $"The export changes {string.Join(", ", tintFields)} but has no regenerated FaceTint; the face color would not match the body (dark face).", subject));
        }
    }

    private static IReadOnlyList<ModKey> Verify(
        LoadOrderSession session, CatalogQueries queries, string pluginPath, ModKey patchKey, int expectedCount, bool esl,
        IReadOnlyList<(FormKey Npc, FaceAssignment Face, FormKey? HairColor)> expectations,
        IReadOnlyDictionary<FormKey, IReadOnlySet<string>> allowedByNpc, out IReadOnlyList<NpcSemanticDiff> semanticDiffs,
        List<Issue> issues)
    {
        using var written = SkyrimMod.CreateFromBinaryOverlay(
            new ModPath(patchKey, pluginPath), SkyrimRelease.SkyrimSE,
            new BinaryReadParameters { MasterFlagsLookup = session.MasterStyles });

        var masters = written.ModHeader.MasterReferences.Select(m => m.Master).ToList();
        var lastIndex = -1;
        foreach (var master in masters)
        {
            var plugin = session.Find(master)
                ?? throw new WorkerException(ErrorCodes.ValidationFailed, $"Verification failed: master '{master}' is not in the load order.");
            if (plugin.LoadIndex < lastIndex)
            {
                throw new WorkerException(ErrorCodes.ValidationFailed, "Verification failed: masters are not in load order.");
            }

            lastIndex = plugin.LoadIndex;
        }

        if (esl != written.ModHeader.Flags.HasFlag(SkyrimModHeader.HeaderFlag.Small))
        {
            throw new WorkerException(ErrorCodes.ValidationFailed, "Verification failed: ESL flag mismatch after writing.");
        }

        var npcs = written.Npcs.ToDictionary(n => n.FormKey);
        if (npcs.Count != expectedCount)
        {
            throw new WorkerException(ErrorCodes.ValidationFailed,
                $"Verification failed: expected {expectedCount} NPC overrides, found {npcs.Count}.");
        }

        // The written record must say exactly what the regenerated FaceGen was built from.
        foreach (var (key, face, hair) in expectations)
        {
            if (!npcs.TryGetValue(key, out var npc))
            {
                throw new WorkerException(ErrorCodes.ValidationFailed, $"Verification failed: {key} missing from the plugin.");
            }

            if (face.OnlyFields is { } only)
            {
                // Minimal change, re-read from the file: the face is the winner's except the allowed fields.
                if (!session.LinkCache.TryResolve<INpcGetter>(key, out var original))
                {
                    throw new WorkerException(ErrorCodes.ValidationFailed, $"Verification failed: winning record of {key} not found.");
                }

                var extra = ChangedFields(original, npc).Except(only, StringComparer.Ordinal).ToList();
                if (extra.Count > 0)
                {
                    throw new WorkerException(ErrorCodes.ValidationFailed,
                        $"Verification failed: {key} changes {string.Join(", ", extra)} beyond {string.Join(", ", only)} after writing.");
                }

                if (npc.HairColor.FormKeyNullable != hair)
                {
                    throw new WorkerException(ErrorCodes.ValidationFailed, $"Verification failed: hair color of {key} differs after writing.");
                }

                // A copied face: every copied field is the source version's, re-read from the file.
                if (face.CopyFaceFrom is { } sourcePlugin)
                {
                    if (session.Find(ModKey.FromFileName(sourcePlugin)) is not { } plugin || !plugin.Mod.Npcs.RecordCache.TryGetValue(key, out var source))
                    {
                        throw new WorkerException(ErrorCodes.ValidationFailed, $"Verification failed: {sourcePlugin}'s version of {key} not found.");
                    }

                    var differ = ChangedFields(source, npc).Intersect(only, StringComparer.Ordinal).ToList();
                    if (differ.Count > 0)
                    {
                        throw new WorkerException(ErrorCodes.ValidationFailed,
                            $"Verification failed: {string.Join(", ", differ)} of {key} differ from {sourcePlugin} after writing.");
                    }
                }

                continue;
            }

            bool Req(string field) => face.RequestedFields is not { } requested || requested.Contains(field);
            if (face.Values is { } v)
            {
                var sliders = FaceRecipeQueries.Sliders(npc.FaceMorph);
                for (var i = 0; i < (Req("FaceMorph") ? 18 : 0); i++)
                {
                    if (Math.Abs(sliders[i] - Math.Clamp(v.Sliders[i], -1f, 1f)) > 1e-5f)
                    {
                        throw new WorkerException(ErrorCodes.ValidationFailed, $"Verification failed: NAM9[{i}] of {key} differs after writing.");
                    }
                }

                if (Req("FaceParts") && (npc.FaceParts is not { } fp || unchecked((int)fp.Nose) != v.Presets[0] || unchecked((int)fp.Eyes) != v.Presets[2]
                    || unchecked((int)fp.Mouth) != v.Presets[3]))
                {
                    throw new WorkerException(ErrorCodes.ValidationFailed, $"Verification failed: NAMA of {key} differs after writing.");
                }

                if (Req("TintLayers") && npc.TintLayers.Count != v.Tints.Count)
                {
                    throw new WorkerException(ErrorCodes.ValidationFailed, $"Verification failed: tint layers of {key} differ after writing.");
                }

                if (Req("HairColor") && npc.HairColor.FormKeyNullable != hair)
                {
                    throw new WorkerException(ErrorCodes.ValidationFailed, $"Verification failed: hair color of {key} differs after writing.");
                }
            }

            if (face.HeadParts is { } parts && Req("HeadParts"))
            {
                var wanted = parts.Select(p => queries.TryParseAnyFormKey(p, out var k) ? k : FormKey.Null).ToList();
                if (!npc.HeadParts.Select(h => h.FormKey).SequenceEqual(wanted))
                {
                    throw new WorkerException(ErrorCodes.ValidationFailed, $"Verification failed: head parts of {key} differ after writing.");
                }
            }
        }

        // Safe patch: every NPC_ field of every override (not only the face ones) against the winner.
        semanticDiffs = NpcSafePatch.CheckAll(session, patchKey, npcs.Values, allowedByNpc, "this face/outfit export");
        // A copied face was not edited: say where each value comes from.
        var sources = expectations.Where(e => e.Face.CopyFaceFrom is not null).ToDictionary(e => e.Npc.ToString(), e => e.Face.CopyFaceFrom!);
        semanticDiffs = semanticDiffs.Select(d => sources.TryGetValue(d.Npc, out var from)
            ? d with { Changes = d.Changes.Select(c => c with { Reason = $"Copiado de {from}: el rostro del FaceGen que ya usa el juego" }).ToList() }
            : d).ToList();

        foreach (var record in written.EnumerateMajorRecords())
        {
            foreach (var link in record.EnumerateFormLinks())
            {
                if (link.IsNull || link.FormKey.ModKey == patchKey)
                {
                    continue;
                }

                if (!session.LinkCache.TryResolve(link.FormKey, link.Type, out _))
                {
                    issues.Add(Issue.Warning("UnresolvedReference",
                        $"{record.FormKey} references {link.FormKey}, which does not resolve in active load order.",
                        record.FormKey.ToString()));
                }
            }
        }

        return masters;
    }

    private static string Sha256Of(string path) => Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(path)));

    private static string UniqueEditorId(string candidate, HashSet<string> used)
    {
        var baseId = Regex.Replace(candidate, @"[^A-Za-z0-9_]", "_");
        if (baseId.Length > 90) baseId = baseId[..90];
        var id = baseId;
        for (var n = 2; !used.Add(id); n++)
        {
            id = $"{baseId}{n}";
        }
        return id;
    }

    private static string Truncate(string value, int max) => value.Length <= max ? value : value[..max];
