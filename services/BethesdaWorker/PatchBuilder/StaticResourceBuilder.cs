using System.Security.Cryptography;
using System.Text.RegularExpressions;
using Mutagen.Bethesda;
using Mutagen.Bethesda.Plugins;
using Mutagen.Bethesda.Plugins.Binary.Parameters;
using Mutagen.Bethesda.Skyrim;
using Noggog;
using SkyrimNpcStudio.Worker.Contracts;
using SkyrimNpcStudio.Worker.PluginReader;
using SkyrimNpcStudio.Worker.Validation;

namespace SkyrimNpcStudio.Worker.PatchBuilder;

/// <summary>
/// Character Forge static resource (Type A + plugin): copies the NIF/DDS files the studio exported and verified into the staged
/// mod folder (each one re-hashed against the studio's manifest) and writes a new plugin with exactly one STAT whose model is the
/// NIF and whose OBND are the bounds the studio re-read from it. The plugin has no masters and overrides nothing. Read back with
/// Mutagen before the packager commits anything.
/// </summary>
internal static partial class StaticResourceBuilder
{
    public const int MaxFiles = 64;
    public const int MaxRelativePathLength = 200;

    [GeneratedRegex(@"^[A-Za-z][A-Za-z0-9_]{0,63}$")]
    private static partial Regex EditorIdPattern();

    // Words of letters, digits, _ and -, separated by single spaces (no leading or trailing space, which Windows drops).
    [GeneratedRegex(@"^[A-Za-z0-9_\-]+( [A-Za-z0-9_\-]+)*$")]
    private static partial Regex SegmentPattern();

    [GeneratedRegex(@"^(CON|PRN|AUX|NUL|COM[0-9]|LPT[0-9])$", RegexOptions.IgnoreCase)]
    private static partial Regex DeviceName();

    public static BuiltPatch Build(LoadOrderSession session, ExportForgeResourceRequest request, string pluginPath, string stagedModDir,
        CancellationToken ct)
    {
        if (!EditorIdPattern().IsMatch(request.EditorId ?? string.Empty))
        {
            throw new WorkerException(ErrorCodes.InvalidArgument,
                $"'{request.EditorId}' is not an allowed EditorID (a letter, then letters, digits or _; at most 64).");
        }

        var (min, max) = Bounds(request);
        var files = NormalizeFiles(request.Files);
        var model = NormalizeRelative(request.ModelPath ?? string.Empty, "model path");
        var modelFile = "meshes/" + model;
        if (!model.EndsWith(".nif", StringComparison.OrdinalIgnoreCase) ||
            !files.Any(f => string.Equals(f.Relative, modelFile, StringComparison.OrdinalIgnoreCase)))
        {
            throw new WorkerException(ErrorCodes.InvalidArgument, $"The model '{request.ModelPath}' must be one of the packaged .nif files.");
        }

        var dataDir = SourceData(request.SourceDirectory);
        foreach (var file in files)
        {
            ct.ThrowIfCancellationRequested();
            var bytes = ReadInside(dataDir, file.Relative);
            var sha = Convert.ToHexString(SHA256.HashData(bytes));
            if (!string.Equals(sha, file.Sha256, StringComparison.OrdinalIgnoreCase))
            {
                throw new WorkerException(ErrorCodes.ValidationFailed,
                    $"'{file.Relative}' does not match the hash the studio recorded (expected {file.Sha256}, found {sha}); nothing was written.");
            }

            // The bytes just hashed are the ones written: the source cannot change between the check and the copy.
            var target = Path.Combine(stagedModDir, file.Relative.Replace('/', Path.DirectorySeparatorChar));
            Directory.CreateDirectory(Path.GetDirectoryName(target)!);
            File.WriteAllBytes(target, bytes);
        }

        var key = ModKey.FromFileName(request.PluginName);
        var mod = new SkyrimMod(key, SkyrimRelease.SkyrimSE);
        mod.ModHeader.Author = request.Author;
        mod.ModHeader.Description = request.Description ?? "Generated by Skyrim NPC Studio (Character Forge)";
        if (request.EslFlag)
        {
            mod.ModHeader.Flags |= SkyrimModHeader.HeaderFlag.Small;
        }

        var stat = mod.Statics.AddNew(request.EditorId);
        stat.Model = new Model { File = model.Replace('/', '\\') };
        stat.ObjectBounds = new ObjectBounds { First = min, Second = max };
        if (request.EslFlag && stat.FormKey.ID is < OutfitPatchBuilder.LightRangeMin or > OutfitPatchBuilder.LightRangeMax)
        {
            throw new WorkerException(ErrorCodes.ValidationFailed, $"ESL flag rejected: new record {stat.FormKey} is outside the light-plugin range 0x800–0xFFF.");
        }

        mod.WriteToBinary(pluginPath, new BinaryWriteParameters
        {
            MastersListOrdering = new MastersListOrderingByLoadOrder(session.Plugins.Select(p => p.ModKey).ToArray()),
            MasterFlagsLookup = session.MasterStyles,
        });
        Verify(session, pluginPath, key, stat.FormKey, request, model.Replace('/', '\\'), min, max);
        foreach (var file in files)
        {
            var copied = Path.Combine(stagedModDir, file.Relative.Replace('/', Path.DirectorySeparatorChar));
            if (!string.Equals(Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(copied))), file.Sha256, StringComparison.OrdinalIgnoreCase))
            {
                throw new WorkerException(ErrorCodes.ValidationFailed, $"Verification failed: the copy of '{file.Relative}' differs from its source.");
            }
        }

        var issues = new List<Issue>
        {
            Issue.Warning("NoCollision",
                "The NIF has no collision (bhkCollisionObject): the static is visible but the player and objects pass through it."),
            Issue.Info("InGameTest",
                $"Test it in an isolated MO2 profile: in the console, 'help {request.EditorId} 4' shows the load-order FormID of the STAT, then 'player.placeatme <FormID>'."),
        };
        var records = new[] { new ExportedRecord { FormKey = stat.FormKey.ToString(), RecordType = "STAT", EditorId = request.EditorId, Kind = "new" } };
        return new BuiltPatch(pluginPath, [], request.EslFlag, records, [], issues);
    }

    /// <summary>The written plugin, read back: no masters, the ESL flag asked for, and exactly the one STAT with its model and bounds.</summary>
    private static void Verify(LoadOrderSession session, string pluginPath, ModKey key, FormKey expected, ExportForgeResourceRequest request,
        string model, P3Int16 min, P3Int16 max)
    {
        using var written = SkyrimMod.CreateFromBinaryOverlay(new ModPath(key, pluginPath), SkyrimRelease.SkyrimSE,
            new BinaryReadParameters { MasterFlagsLookup = session.MasterStyles });
        void Require(bool condition, string what)
        {
            if (!condition)
            {
                throw new WorkerException(ErrorCodes.ValidationFailed, $"Verification failed: {what} after writing {key}.");
            }
        }

        Require(written.ModHeader.MasterReferences.Count == 0, "the plugin has masters");
        Require(request.EslFlag == written.ModHeader.Flags.HasFlag(SkyrimModHeader.HeaderFlag.Small), "ESL flag mismatch");
        var records = written.EnumerateMajorRecords().ToList();
        Require(records.Count == 1 && written.Statics.Count == 1, $"expected one STAT, found {records.Count} record(s)");
        var stat = written.Statics.First();
        Require(stat.FormKey == expected && stat.EditorID == request.EditorId, "the STAT FormKey or EditorID changed");
        Require(string.Equals(stat.Model?.File.GivenPath, model, StringComparison.OrdinalIgnoreCase), $"the STAT model is '{stat.Model?.File.GivenPath}'");
        Require(stat.ObjectBounds.First == min && stat.ObjectBounds.Second == max, "the STAT bounds changed");
    }

    private static (P3Int16 Min, P3Int16 Max) Bounds(ExportForgeResourceRequest request)
    {
        if (request.BoundsMin is not { Count: 3 } lo || request.BoundsMax is not { Count: 3 } hi)
        {
            throw new WorkerException(ErrorCodes.InvalidArgument, "Bounds need three coordinates each (x, y, z).");
        }

        if (lo[0] > hi[0] || lo[1] > hi[1] || lo[2] > hi[2] || (lo[0] == hi[0] && lo[1] == hi[1] && lo[2] == hi[2]))
        {
            throw new WorkerException(ErrorCodes.InvalidArgument, "The lower bounds must not exceed the upper ones, and the box cannot be empty.");
        }

        return (new P3Int16(lo[0], lo[1], lo[2]), new P3Int16(hi[0], hi[1], hi[2]));
    }

    private static List<(string Relative, string Sha256)> NormalizeFiles(IReadOnlyList<ForgeResourceFile>? files)
    {
        if (files is not { Count: > 0 } || files.Count > MaxFiles)
        {
            throw new WorkerException(ErrorCodes.InvalidArgument, $"Send between 1 and {MaxFiles} files.");
        }

        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var result = new List<(string, string)>();
        foreach (var file in files)
        {
            var relative = NormalizeRelative(file.RelativePath ?? string.Empty, "file");
            var allowed = relative.StartsWith("meshes/", StringComparison.OrdinalIgnoreCase) && relative.EndsWith(".nif", StringComparison.OrdinalIgnoreCase)
                       || relative.StartsWith("textures/", StringComparison.OrdinalIgnoreCase) && relative.EndsWith(".dds", StringComparison.OrdinalIgnoreCase);
            if (!allowed)
            {
                throw new WorkerException(ErrorCodes.InvalidArgument, $"'{file.RelativePath}': only meshes/*.nif and textures/*.dds can be packaged.");
            }

            if (file.Sha256 is not { Length: 64 } sha || !sha.All(Uri.IsHexDigit))
            {
                throw new WorkerException(ErrorCodes.InvalidArgument, $"'{file.RelativePath}' needs its SHA-256 (64 hexadecimal digits).");
            }

            if (!seen.Add(relative))
            {
                throw new WorkerException(ErrorCodes.InvalidArgument, $"'{file.RelativePath}' is listed twice.");
            }

            result.Add((relative, sha));
        }

        return result;
    }

    /// <summary>"a/b/c.ext" with "/" separators; refuses rooted, parent, empty or odd segments (no drive letters, no device names).</summary>
    private static string NormalizeRelative(string path, string what)
    {
        var relative = path.Replace('\\', '/');
        var segments = relative.Split('/');
        if (relative.Length is 0 or > MaxRelativePathLength || Path.IsPathRooted(path) || relative.Contains(':') ||
            segments.Any(s => s.Length == 0 || s is "." or ".." || !SegmentPattern().IsMatch(Path.GetFileNameWithoutExtension(s)) ||
                              DeviceName().IsMatch(Path.GetFileNameWithoutExtension(s)) ||
                              Path.GetExtension(s) is { Length: > 0 } ext && ext is not (".nif" or ".dds" or ".NIF" or ".DDS")))
        {
            throw new WorkerException(ErrorCodes.InvalidArgument, $"The {what} path '{path}' is not a safe relative path.");
        }

        return relative;
    }

    private static string SourceData(string? sourceDirectory)
    {
        if (string.IsNullOrWhiteSpace(sourceDirectory) || !Path.IsPathFullyQualified(sourceDirectory))
        {
            throw new WorkerException(ErrorCodes.InvalidArgument, "The source must be the absolute folder of an exported package.");
        }

        var data = Path.Combine(sourceDirectory, "Data");
        if (!Directory.Exists(data))
        {
            throw new WorkerException(ErrorCodes.InvalidArgument, $"'{sourceDirectory}' has no Data folder.");
        }

        return ExportDestinationPolicy.RealDirectory(data);
    }

    /// <summary>The file's bytes, refusing links and anything whose resolved folder is not inside the package's Data folder.</summary>
    private static byte[] ReadInside(string dataDir, string relative)
    {
        var full = Path.GetFullPath(Path.Combine(dataDir, relative.Replace('/', Path.DirectorySeparatorChar)));
        var info = new FileInfo(full);
        if (!info.Exists)
        {
            throw new WorkerException(ErrorCodes.InvalidArgument, $"'{relative}' does not exist in the package.");
        }

        var folder = ExportDestinationPolicy.RealDirectory(info.DirectoryName!);
        var comparison = OperatingSystem.IsWindows() ? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal;
        if (info.Attributes.HasFlag(FileAttributes.ReparsePoint) || !folder.StartsWith(dataDir + Path.DirectorySeparatorChar, comparison))
        {
            throw new WorkerException(ErrorCodes.InvalidArgument, $"'{relative}' is a link or leaves the package's Data folder.");
        }

        return File.ReadAllBytes(full);
    }
}
